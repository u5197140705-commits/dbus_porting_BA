static inline uint8_t DLL_GET_COMMUNICATION_PARTNER(uint8_t x)           {return ((uint8_t)(((x) & (uint8_t) 0xF0U) >> 4));} //!< Extracts the communication partner from a target address. Upper nibble of TA is communication partner, lower nibble is subsystem. DLL_GET_COMMUNICATION_PARTNER shifts the upper nibble down.
static inline uint8_t DLL_IGNORE_SUBSYSTEM_IN_TARGET_ADDRESS(uint8_t x)  {return ((uint8_t)((x) & (uint8_t)0xF0U));}         //!< Extracts the communication partner from a target address. Upper nibble of TA is communication partner, lower nibble is subsystem. Unlike DLL_GET_COMMUNICATION_PARTNER, the communication partner is not shifted to the lower nibble.
static inline uint8_t DLL_GET_SUBSYSTEM(uint8_t x)                       {return ((uint8_t)((x) & (uint8_t)0x0FU));}         //!< Extracts the subsystem from a target address. Upper nibble of TA is communication partner, lower nibble is subsystem.
static inline uint8_t DLL_GET_ACKNOWLEDGE(uint8_t x)                     {return ((uint8_t)((x) & (uint8_t)0x0FU));}         //!< Extracts the acknowledgement from the acknowledgement-byte received from another communication partner. The Acknowledge-byte consists of the communication partner address in the upper nibble, and the acknowledgement in the lower nibble.



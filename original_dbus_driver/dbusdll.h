/**
 Function, which returns a newly received message (if any present) -  the oldest
 not-yet-picked-up message is reported first.

 If the message, which is picked up cannot be processed immediately, this function will return
 the same pointer (to the same message) all the time, until the release function
 (DLL_vReleaseDataFromReceivedMessage) has been called to indicate, that the message
 has been processed, and the data bytes in the input buffer can be used for new incoming messages.
 If no message is present in the input buffer a NULL pointer is returned.

\return
 a pointer to the oldest message, which was received (NULL if none present).
 The data should be transported to the user (typically application) via service functions,
 as the data is not buffered, succeedingly.\n
\b type       : tMessage *

*/
TbusMessage * DLL_ptReceiveMessage(void);

/**
 This function signalises whether the bus is ready for transmission, i.e. that no other node is transmitting
 anything. This function returns true when a message may be transmitted.

\note It is important that this function is not called when receive interrupts are enabled!

\return
\b type       : bool\n
\b range      : 0 = false / not ready, all other values = true / ready

*/
bool DLL_bIsBusReadyForTransmission(void);

/**
DEPRECATED, left for legacy reasons
Function, which may be called to send a message of type TbusMessage onto the bus.

NOT to use for sending of service messages, NOT to use for messages send via BAL with repetitions.
For the purposes mentioned above, DLL_bTransmitMessage is to be used.
In case of Silent Mode, the return value will be false.

\param ptMessageToTransmit
psMessageID is a pointer to the message, which is about to be sent\n
\b type       : TbusMessage

\param uiUserCode
UserCode is any specific code/index/number, which the overlaying layer associates with this specific message.
UserCode is returned by the message completion function: DLL_vMessageTransmitted(uint8_t Acknowledge, uint16_t UserCode).
If there is no valid user code, use the value zero\n
\b type       : uint16_t
\b range      : 0..65535
 */
bool DLL_bSendMessage(TbusMessage *ptMessageToTransmit, uint16_t uiUserCode);

/**
Function called to initiate transmission of a message on the bus.

Whenever bus application layer is implemented this function is to be used instead of
DLL_bSendMessage(tMessage *psMessageToTransmit, uint8_t UserCode),
which is not able to pick up data from a service interface (the second parameter in DLL_bTransmitMessage).

\param tMessageID
psMessageID is a pointer to the message identifier, which is about to be sent\n
\b type       : TbusIdentifier

\param tServiceFunc
ServiceFunc is the interface, where the data, which is about to be sent, can be picked up\n
\b type       : TbusService

\param ucDataLength
Length of the data to be sent.\n
\b type       : uint8_t

\param uiUserCode
UserCode is any specific code/index/number, which the overlaying layer associates with this specific message.
UserCode is returned by the message completion function: DLL_vMessageTransmitted(uint8_t Acknowledge, uint16_t UserCode).
If there is no valid user code, use the value zero\n
\b type       : uint16_t\n
\b range      : 0..65535

\return
\b type       : bool\n
\b range      : 0 = false (meaning: transmission could not be initiated), all other values = true
 (meaning: transmission initiated)

*/

bool DLL_bTransmitMessage(TbusIdentifier tMessageID, TbusService tServiceFunc, uint8_t ucDataLength, uint16_t uiUserCode);


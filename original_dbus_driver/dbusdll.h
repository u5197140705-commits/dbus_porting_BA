/*Acks*/
#define DLL_ACK_NOT_RECEIVED   ((uint8_t)0x00U)    //!< CommunicationPartner 0 means broadcast, hence it cannot be returned by any (one) communication partner. The AckType 0 is not defined as any acknowledgement which can be returned from any node, hence it is used to signalise a missing acknowledgement.
#define DLL_ACK_BUSY           ((uint8_t)0x03U)    //!< By Full input buffer or message too long for input buffer.
#define DLL_ACK_WRONG          ((uint8_t)0x07U)    //!< Error by reception - wrong crc.
#define DLL_ACK_OK             ((uint8_t)0x0AU)    //!< Successful reception (crc ok).

#define DLL_ACK_TRANSMISSION_ABORTED  ((uint8_t)0x0FU)        //!< This error definition is used to notify the overlying layer when a collision is terminating the ongoing transmission (instead of calling an error function, the less code costing alternative to include this ).

#define DLL_CRC_INIT   0x0000U      //!< Initial value of crc


